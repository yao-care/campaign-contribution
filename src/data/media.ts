/** 長輩圖三種版型共用的鉤子文案。鉤子是「會被罰」而不是日期本身。 */
export interface Hook {
  /** C 對話框：使用者問的話 */
  ask: string;
  /** C 對話框：紅底大字的答案 */
  answer: string;
  /** C 對話框：答案底下的補充 */
  answerSub: string;
  /** A 警示：紅色標籤上的對象 */
  who: string;
  /** A 警示：三行大字，第三行會標紅 */
  warn: [string, string, string];
  /** A 警示：大字底下的補充 */
  warnSub: string;
  /** B 長輩圖：白卡最上方的引導句 */
  lead: string;
  /** B 長輩圖：紅色大字，三行以內 */
  big: string[];
  /** B 長輩圖：大字底下的叮嚀 */
  care: string;
}

export interface MediaItem {
  slug: string;
  /** 素材上的大字 */
  headline: string;
  /** 大字底下的一行補充 */
  sub: string;
  /** 頁面上的完整說明，這頁本身是 SEO 資產 */
  body: string[];
  /** 圖片的替代文字，描述性而非裝飾性 */
  alt: string;
  /** 可直接複製貼 LINE 的純文字 */
  lineText: string;
  topic: '資格' | '金額' | '時間' | '程序' | '稅務' | '罰則';
  lawRefs: { label: string; href: string }[];
  formats: MediaFormat[];
  hook: Hook;
  /** 短影音腳本與分鏡，僅 video-script 用 */
  shots?: { t: string; visual: string; vo: string }[];
}


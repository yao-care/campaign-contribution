/**
 * 產生 §10.4 的四份開放資料集到 public/data/，CSV 與 JSON 各一份。
 * 資料集是引用磁鐵；機關掛名的話可再上架政府資料開放平臺。
 * 所有欄位均來自已核對過的資料層，不另行改寫。
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { readFile } from 'node:fs/promises';

const law = JSON.parse(await readFile('src/data/law.json', 'utf-8'));
const villages = JSON.parse(await readFile('src/data/villages.json', 'utf-8'));

const csv = (rows) => rows.map((r) =>
  r.map((c) => {
    const s = String(c ?? '');
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  }).join(',')).join('\n') + '\n';

await mkdir('public/data', { recursive: true });
const out = async (name, header, rows, meta) => {
  await writeFile(`public/data/${name}.csv`, '﻿' + csv([header, ...rows]));
  await writeFile(`public/data/${name}.json`, JSON.stringify({
    ...meta,
    fields: header,
    count: rows.length,
    generatedAt: new Date().toISOString(),
    records: rows.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]]))),
  }, null, 2) + '\n');
  console.log(`${name}: ${rows.length} 筆`);
};

